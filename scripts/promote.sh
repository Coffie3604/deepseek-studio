#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════
# promote.sh — sandbox → production, gated on tests
#
# Replaces patch-all.sh / patch-index-sync.sh / patch-server-sync.sh.
# Those three scripts each copied a hand-maintained list of files and
# none of them checked that the result parsed. This one diffs the two
# checkouts, refuses to run if `npm test` fails, and copies only what
# actually changed.
#
# Usage:
#   scripts/promote.sh            # dry run: show what would change
#   scripts/promote.sh --apply    # actually copy
#   scripts/promote.sh --apply --with-android
#
# Layout assumed:
#   ~/projects/deepseek-editor-sandbox   (this repo, port 3002)
#   ~/projects/deepseek-editor           (production, port 3001)
# ═══════════════════════════════════════════════════════════════════
set -euo pipefail

SANDBOX="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROD="${DS_PROD_DIR:-$HOME/projects/deepseek-editor}"

APPLY=0
WITH_ANDROID=0
for arg in "$@"; do
  case "$arg" in
    --apply)        APPLY=1 ;;
    --with-android) WITH_ANDROID=1 ;;
    -h|--help)      sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "unknown flag: $arg" >&2; exit 2 ;;
  esac
done

# Paths that are sandbox-only and must never be promoted.
#
# NOTE: this list is the whole safety story. Anything not listed here gets
# copied verbatim into production, so dead scaffolding, editor backups and
# one-shot patch scripts must be named explicitly. A previous version of this
# script omitted them and pushed a stale modular UI over production's newer
# monolithic index.html — see the "direction" guard below, which now makes
# that class of mistake impossible to apply silently.
EXCLUDES=(
  "node_modules"
  ".git"
  ".patch-backup"
  ".chk"
  "ds-run.log"
  "ROADMAP.md"
  "scripts/promote.sh"
  # One-shot patch scripts, superseded by this file.
  "patch-all.sh"
  "patch-index-sync.sh"
  "patch-server-sync.sh"
  # Dead code-injection helpers from the pre-modular era.
  "_tools"
  # Editor/script backups must never ship.
  "*.bak"
  "*.bak.*"
  "*.orig"
  "*.ds-bak"
  "*.pre-fix"
)

# Files whose content is *generated* in production and must not be clobbered.
# package-lock.json is regenerated by `npm install` on the target; copying the
# sandbox's lock over production's can pin a different dependency tree.
PROTECTED=(
  "package-lock.json"
)

# Files that are expected to differ by design (sandbox runs on 3002, shows a
# STAGING badge, etc.). They are still promoted, but the diff is reported so a
# reviewer can confirm the difference is intentional.
EXPECTED_DIFF=(
  "server.js"
  "public/index.html"
  "public/app.css"
  "public/sw.js"
  "package.json"
  "install.sh"
  ".github/workflows/ci.yml"
)

say()  { printf '\033[1m%s\033[0m\n' "$*"; }
ok()   { printf '  \033[32m✓\033[0m %s\n' "$*"; }
warn() { printf '  \033[33m!\033[0m %s\n' "$*"; }
die()  { printf '\033[31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

[ -d "$PROD" ] || die "production checkout not found: $PROD
Set DS_PROD_DIR=/path/to/deepseek-editor and retry."

say "sandbox:    $SANDBOX"
say "production: $PROD"
echo

# ── 1. gate on tests ───────────────────────────────────────────────
say "1. tests"
( cd "$SANDBOX" && npm test --silent ) || die "npm test failed — refusing to promote."
ok "npm test passed"

# ── 2. syntax-check every JS file that would move ──────────────────
say "2. syntax"
fail=0
while IFS= read -r f; do
  case "$f" in
    *.js)
      if ! node --check "$SANDBOX/$f" 2>/dev/null; then
        # ESM files need the module flag; retry as a module.
        if ! node --input-type=module --check < "$SANDBOX/$f" 2>/dev/null; then
          warn "syntax error: $f"; fail=1
        fi
      fi
      ;;
  esac
done < <(cd "$SANDBOX" && git ls-files 2>/dev/null || find . -type f -name '*.js' -not -path './node_modules/*')
[ "$fail" -eq 0 ] || die "syntax errors above — refusing to promote."
ok "all JS parses"

# ── 3. diff ────────────────────────────────────────────────────────
say "3. changes"
CHANGED=()
while IFS= read -r f; do
  skip=0
  for ex in "${EXCLUDES[@]}"; do
    # Match the pattern itself, anything under it (dir), and the basename
    # (so "*.bak" catches "public/app.css.bak").
    case "$f" in
      "$ex"|"$ex"/*|*/"$ex") skip=1 ;;
    esac
    case "$(basename "$f")" in $ex) skip=1 ;; esac
  done
  for pr in "${PROTECTED[@]}"; do
    case "$f" in "$pr") skip=1 ;; esac
  done
  [ "$skip" -eq 1 ] && continue
  if [ ! -e "$PROD/$f" ] || ! cmp -s "$SANDBOX/$f" "$PROD/$f"; then
    CHANGED+=("$f")
  fi
done < <(cd "$SANDBOX" && find . -type f \
           -not -path './node_modules/*' -not -path './.git/*' \
           -not -path './.patch-backup/*' -not -path './.chk/*' \
           | sed 's|^\./||' | sort)

if [ "${#CHANGED[@]}" -eq 0 ]; then
  ok "nothing to promote — production is up to date"
  exit 0
fi

for f in "${CHANGED[@]}"; do
  if [ ! -e "$PROD/$f" ]; then
    printf '  \033[32m+\033[0m %s\n' "$f"
  else
    printf '  \033[33m~\033[0m %s\n' "$f"
  fi
done
echo
say "${#CHANGED[@]} file(s) differ"

# ── 3b. direction guard ────────────────────────────────────────────
# The sandbox is *staging*: it is only ever allowed to move production
# forward. If production's copy of a file is newer than the sandbox's, the
# sandbox is stale and copying would be a regression, not a promotion.
# Compare git commit timestamps where both sides are tracked; fall back to
# mtime for untracked files.
say "3b. direction"
STALE=()
for f in "${CHANGED[@]}"; do
  [ -e "$PROD/$f" ] || continue
  s_ts=$( cd "$SANDBOX" && git log -1 --format=%ct -- "$f" 2>/dev/null || true )
  p_ts=$( cd "$PROD"    && git log -1 --format=%ct -- "$f" 2>/dev/null || true )
  if [ -n "$s_ts" ] && [ -n "$p_ts" ]; then
    if [ "$p_ts" -gt "$s_ts" ]; then STALE+=("$f"); fi
  else
    # Untracked on one side — fall back to modification time.
    if [ "$PROD/$f" -nt "$SANDBOX/$f" ]; then STALE+=("$f"); fi
  fi
done

if [ "${#STALE[@]}" -gt 0 ]; then
  warn "production is NEWER than the sandbox for ${#STALE[@]} file(s):"
  for f in "${STALE[@]}"; do printf '    \033[33m↓\033[0m %s\n' "$f"; done
  echo
  warn "Promoting these would roll production backwards."
  warn "Rebase the sandbox onto production first:"
  echo "    cd $PROD && git log --oneline -5 -- <file>"
  echo "    # port the production changes into the sandbox, re-run this script"
  echo
  if [ "$APPLY" -eq 1 ] && [ "${FORCE:-0}" != "1" ]; then
    die "refusing to apply — re-run with FORCE=1 to override (not recommended)"
  fi
else
  ok "sandbox is ahead of production for every changed file"
fi

# ── 4. apply ───────────────────────────────────────────────────────
if [ "$APPLY" -eq 0 ]; then
  echo
  warn "dry run — re-run with --apply to copy"
  exit 0
fi

say "4. copying"
for f in "${CHANGED[@]}"; do
  mkdir -p "$PROD/$(dirname "$f")"
  cp -p "$SANDBOX/$f" "$PROD/$f"
  ok "$f"
done

# Files that exist in production but were removed in the sandbox are NOT
# deleted automatically — that is a destructive action and needs a human.
REMOVED=()
while IFS= read -r f; do
  [ -e "$SANDBOX/$f" ] && continue
  skip=0
  for ex in "${EXCLUDES[@]}"; do
    case "$f" in "$ex"|"$ex"/*) skip=1 ;; esac
    case "$(basename "$f")" in $ex) skip=1 ;; esac
  done
  [ "$skip" -eq 1 ] && continue
  REMOVED+=("$f")
done < <(cd "$PROD" && find . -type f \
           -not -path './node_modules/*' -not -path './.git/*' \
           -not -path './.patch-backup/*' -not -path './.chk/*' \
           | sed 's|^\./||' | sort)

if [ "${#REMOVED[@]}" -gt 0 ]; then
  echo
  warn "present in production but absent from the sandbox (left untouched):"
  for f in "${REMOVED[@]}"; do printf '    \033[33m-\033[0m %s\n' "$f"; done
  warn "delete these by hand if they are genuinely dead"
fi

# ── 5. verify production still parses ──────────────────────────────
say "5. verify production"
( cd "$PROD" && node --check server.js ) || die "production server.js no longer parses!"
ok "production server.js parses"

echo
say "done — restart the production backend to pick up the changes:"
echo "  cd $PROD && node server.js"
